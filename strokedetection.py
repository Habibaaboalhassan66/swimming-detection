        "# ══════════════════════════════════════════════\n",
        "def identify_stroke_from_path(folder_name: str) -> str:\n",
        "    \"\"\"\n",
        "    Identify stroke type from folder name.\n",
        "    Handles names like:\n",
        "      breaststroke_front_S01 → breaststroke\n",
        "      butterfly_front_S05   → butterfly\n",
        "      freestyle_front_S01   → freestyle (excluded)\n",
        "    \"\"\"\n",
        "    folder_lower = folder_name.lower()\n",
        "    if \"breaststroke\" in folder_lower:\n",
        "        return \"breaststroke\"\n",
        "    elif \"butterfly\" in folder_lower:\n",
        "        return \"butterfly\"\n",
        "    else:\n",
        "        return None  # exclude freestyle and unknown\n",
        "\n",
        "\n",
        "def load_frame(image_path: str, img_size: int) -> np.ndarray:\n",
        "    \"\"\"Load and preprocess a single frame for CNN input.\"\"\"\n",
        "    img = cv2.imread(image_path)\n",
        "    if img is None:\n",
        "        return None\n",
        "    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)\n",
        "    img = cv2.resize(img, (img_size, img_size))\n",
        "    img = img.astype(np.float32) / 255.0  # normalize to [0, 1]\n",
        "    return img\n",
        "\n",
        "\n",
        "def load_dataset(base_paths: list, img_size: int,\n",
        "                 max_per_class: int = 1000) -> tuple:\n",
        "    \"\"\"\n",
        "    Load frames from all stroke subfolders.\n",
        "    Returns (images, labels, class_counts).\n",
        "\n",
        "    max_per_class: limit frames per stroke to balance dataset\n",
        "    \"\"\"\n",
        "    images = []\n",
        "    labels = []\n",
        "    class_counts = {\"breaststroke\": 0, \"butterfly\": 0}\n",
        "\n",
        "    print(\"\\n📂 Loading training dataset...\")\n",
        "\n",
        "    for base_path in base_paths:\n",
        "        base = Path(base_path)\n",
        "        if not base.exists():\n",
        "            print(f\"  ⚠️  Not found: {base_path}\")\n",
        "            continue\n",
        "\n",
        "        # Each subfolder is a video (e.g. breaststroke_front_S01)\n",
        "        for video_folder in sorted(base.iterdir()):\n",
        "            if not video_folder.is_dir():\n",
        "                continue\n",
        "\n",
        "            stroke = identify_stroke_from_path(video_folder.name)\n",
        "            if stroke is None:\n",
        "                continue  # skip freestyle\n",
        "\n",
        "            label = STROKE_LABELS[stroke]\n",
        "\n",
        "            # Get frames from this video\n",
        "            frames = sorted(video_folder.glob(\"*.jpg\"))\n",
        "            if not frames:\n",
        "                continue\n",
        "\n",
        "            # Sample evenly to avoid too many frames from one video\n",
        "            max_from_video = min(50, len(frames))\n",
        "            step  = max(1, len(frames) // max_from_video)\n",
        "            sampled = frames[::step][:max_from_video]\n",
        "\n",
        "            loaded = 0\n",
        "            for frame_path in sampled:\n",
        "                # Check class limit\n",
        "                if class_counts[stroke] >= max_per_class:\n",
        "                    break\n",
        "                img = load_frame(str(frame_path), img_size)\n",
        "                if img is not None:\n",
        "                    images.append(img)\n",
        "                    labels.append(label)\n",
        "                    class_counts[stroke] += 1\n",
        "                    loaded += 1\n",
        "\n",
        "            print(f\"  [{stroke}] {video_folder.name}: {loaded} frames loaded\")\n",
        "\n",
        "    print(f\"\\n  Total frames loaded:\")\n",
        "    for stroke, count in class_counts.items():\n",
        "        print(f\"    {stroke}: {count} frames\")\n",
        "\n",
        "    return np.array(images), np.array(labels), class_counts\n",
        "\n",
        "\n",
        "# ══════════════════════════════════════════════\n",
        "#  ④ CNN MODEL ARCHITECTURE\n",
        "# ══════════════════════════════════════════════\n",
        "def build_stroke_cnn(img_size: int, num_classes: int = 2) -> keras.Model:\n",
        "    \"\"\"\n",
        "    Build CNN for stroke classification.\n",
        "\n",
        "    Architecture:\n",
        "      - MobileNetV2 base (pre-trained on ImageNet) → transfer learning\n",
        "      - Global Average Pooling\n",
        "      - Dense 256 → Dropout → Dense 128 → Dropout\n",
        "      - Output: 2 classes (breaststroke / butterfly)\n",
        "\n",
        "    WHY MobileNetV2:\n",
        "      - Lightweight → runs on Colab CPU/GPU\n",
        "      - Pre-trained on ImageNet → already knows visual features\n",
        "      - Fine-tuned on your frames → learns stroke-specific patterns\n",
        "      - Same fine-tuning principle as your Roboflow model\n",
        "    \"\"\"\n",
        "    # Base model — pre-trained MobileNetV2\n",
        "    base_model = keras.applications.MobileNetV2(\n",
        "        input_shape=(img_size, img_size, 3),\n",
        "        include_top=False,\n",
        "        weights=\"imagenet\"\n",
        "    )\n",
        "\n",
        "    # Freeze base model initially\n",
        "    base_model.trainable = False\n",
        "\n",
        "    # Build full model\n",
        "    inputs = keras.Input(shape=(img_size, img_size, 3))\n",
        "    x = keras.applications.mobilenet_v2.preprocess_input(inputs)\n",
        "    x = base_model(x, training=False)\n",
        "    x = layers.GlobalAveragePooling2D()(x)\n",
        "    x = layers.Dense(256, activation=\"relu\")(x)\n",
        "    x = layers.Dropout(0.3)(x)\n",
        "    x = layers.Dense(128, activation=\"relu\")(x)\n",
        "    x = layers.Dropout(0.3)(x)\n",
        "\n",
        "    if num_classes == 2:\n",
        "        outputs = layers.Dense(1, activation=\"sigmoid\")(x)\n",
        "    else:\n",
        "        outputs = layers.Dense(num_classes, activation=\"softmax\")(x)\n",
        "\n",
        "    model = keras.Model(inputs, outputs)\n",
        "\n",
        "    return model, base_model\n",
        "\n",
        "\n",
        "def compile_model(model: keras.Model, num_classes: int = 2) -> keras.Model:\n",
        "    \"\"\"Compile the CNN model.\"\"\"\n",
        "    if num_classes == 2:\n",
        "        model.compile(\n",
        "            optimizer=keras.optimizers.Adam(learning_rate=1e-3),\n",
        "            loss=\"binary_crossentropy\",\n",
        "            metrics=[\"accuracy\"]\n",
        "        )\n",
        "    else:\n",
        "        model.compile(\n",
        "            optimizer=keras.optimizers.Adam(learning_rate=1e-3),\n",
        "            loss=\"sparse_categorical_crossentropy\",\n",
        "            metrics=[\"accuracy\"]\n",
        "        )\n",
        "    return model\n",
        "\n",
        "\n",
        "# ══════════════════════════════════════════════\n",
        "#  ⑤ TRAINING\n",
        "# ══════════════════════════════════════════════\n",
        "def train_stroke_cnn(images: np.ndarray, labels: np.ndarray) -> tuple:\n",
        "    \"\"\"\n",
        "    Train the stroke detection CNN in two phases:\n",
        "\n",
        "    Phase 1 — Train only the top layers (base frozen)\n",
        "      → Quick learning of stroke-specific features\n",
        "\n",
        "    Phase 2 — Fine-tune the top layers of base model too\n",
        "      → Refine low-level features for swimming context\n",
        "\n",
        "    Returns (model, history)\n",
        "    \"\"\"\n",
        "    print(\"\\n🧠 Building CNN model...\")\n",
        "    model, base_model = build_stroke_cnn(IMG_SIZE)\n",
        "    model = compile_model(model)\n",
        "    model.summary()\n",
        "\n",
        "    # Shuffle data\n",
        "    idx     = np.random.permutation(len(images))\n",
        "    images  = images[idx]\n",
        "    labels  = labels[idx]\n",
        "\n",
        "    # Split train/val\n",
        "    val_size   = int(len(images) * VAL_SPLIT)\n",
        "    x_train, x_val = images[val_size:], images[:val_size]\n",
        "    y_train, y_val = labels[val_size:], labels[:val_size]\n",
        "\n",
        "    print(f\"\\n  Training: {len(x_train)} frames\")\n",
        "    print(f\"  Validation: {len(x_val)} frames\")\n",
        "\n",
        "    # Callbacks\n",
        "    callbacks = [\n",
        "        keras.callbacks.EarlyStopping(\n",
        "            patience=5,\n",
        "            restore_best_weights=True,\n",
        "            monitor=\"val_accuracy\"\n",
        "        ),\n",
        "        keras.callbacks.ReduceLROnPlateau(\n",
        "            factor=0.5,\n",
        "            patience=3,\n",
        "            monitor=\"val_loss\"\n",
        "        ),\n",
        "    ]\n",
        "\n",
        "    # ── Phase 1: Train top layers only ──────────\n",
        "    print(\"\\n📈 Phase 1 — Training top layers (base frozen)...\")\n",
        "    history1 = model.fit(\n",
        "        x_train, y_train,\n",
        "        validation_data=(x_val, y_val),\n",
        "        epochs=EPOCHS,\n",
        "        batch_size=BATCH_SIZE,\n",
        "        callbacks=callbacks,\n",
        "        verbose=1\n",
        "    )\n",
        "\n",
        "    # ── Phase 2: Fine-tune top layers of base ───\n",
        "    print(\"\\n📈 Phase 2 — Fine-tuning (unfreezing top 30 layers)...\")\n",
        "    base_model.trainable = True\n",
        "\n",
        "    # Only unfreeze top 30 layers\n",
        "    for layer in base_model.layers[:-30]:\n",
        "        layer.trainable = False\n",
        "\n",
        "    # Recompile with lower learning rate\n",
        "    model.compile(\n",
        "        optimizer=keras.optimizers.Adam(learning_rate=1e-5),\n",
        "        loss=\"binary_crossentropy\",\n",
        "        metrics=[\"accuracy\"]\n",
        "    )\n",
        "\n",
        "    history2 = model.fit(\n",
        "        x_train, y_train,\n",
        "        validation_data=(x_val, y_val),\n",
        "        epochs=10,\n",
        "        batch_size=BATCH_SIZE,\n",
        "        callbacks=callbacks,\n",
        "        verbose=1\n",
        "    )\n",
        "\n",
        "    return model, history1, history2, x_val, y_val\n",
        "\n",
        "\n",
        "# ══════════════════════════════════════════════\n",
        "#  ⑥ EVALUATION\n",
        "# ══════════════════════════════════════════════\n",
        "def evaluate_model(model: keras.Model,\n",
        "                   x_val: np.ndarray,\n",
        "                   y_val: np.ndarray) -> dict:\n",
        "    \"\"\"Evaluate model on validation set.\"\"\"\n",
        "    print(\"\\n📊 Evaluating model...\")\n",
        "\n",
        "    loss, accuracy = model.evaluate(x_val, y_val, verbose=0)\n",
        "\n",
        "    # Get predictions\n",
        "    preds = model.predict(x_val, verbose=0)\n",
        "    pred_labels = (preds > 0.5).astype(int).flatten()\n",
        "\n",
        "    # Per-class accuracy\n",
        "    for stroke, label_id in STROKE_LABELS.items():\n",
        "        mask     = y_val == label_id\n",
        "        if mask.sum() > 0:\n",
        "            correct  = (pred_labels[mask] == y_val[mask]).sum()\n",
        "            acc      = correct / mask.sum() * 100\n",
        "            print(f\"  {stroke}: {correct}/{mask.sum()} correct ({acc:.1f}%)\")\n",
        "\n",
        "    print(f\"\\n  Overall accuracy: {accuracy*100:.1f}%\")\n",
        "    print(f\"  Loss: {loss:.4f}\")\n",
        "\n",
        "    return {\"accuracy\": accuracy, \"loss\": loss}\n",
        "\n",
        "\n",
        "def plot_training_history(history1, history2) -> None:\n",
