        "\n",
        "\n",
        "# ══════════════════════════════════════════════\n",
        "#  ⑦ STROKE PREDICTION ON NEW VIDEO\n",
        "# ══════════════════════════════════════════════\n",
        "def predict_stroke(model: keras.Model,\n",
        "                   folder_path: str,\n",
        "                   sample_size: int = 20) -> tuple:\n",
        "    \"\"\"\n",
        "    Predict stroke type for a folder of frames.\n",
        "    Samples frames evenly, runs CNN, returns majority vote.\n",
        "\n",
        "    Returns (stroke_name, confidence)\n",
        "    \"\"\"\n",
        "    folder = Path(folder_path)\n",
        "    frames = sorted(folder.rglob(\"*.jpg\"))\n",
        "\n",
        "    if not frames:\n",
        "        print(f\"  ⚠️  No frames found in {folder_path}\")\n",
        "        return None, 0.0\n",
        "\n",
        "    # Sample evenly\n",
        "    step   = max(1, len(frames) // sample_size)\n",
        "    sample = frames[::step][:sample_size]\n",
        "\n",
        "    predictions = []\n",
        "    for frame_path in sample:\n",
        "        img = load_frame(str(frame_path), IMG_SIZE)\n",
        "        if img is None:\n",
        "            continue\n",
        "        img_batch = np.expand_dims(img, axis=0)\n",
        "        pred      = model.predict(img_batch, verbose=0)[0][0]\n",
        "        predictions.append(pred)\n",
        "\n",
        "    if not predictions:\n",
        "        return None, 0.0\n",
        "\n",
        "    avg_pred = np.mean(predictions)\n",
        "\n",
        "    # Binary classification\n",
        "    if avg_pred < 0.5:\n",
        "        stroke     = \"breaststroke\"\n",
        "        confidence = 1.0 - avg_pred\n",
        "    else:\n",
        "        stroke     = \"butterfly\"\n",
        "        confidence = avg_pred\n",
        "\n",
        "    return stroke, float(confidence)\n",
        "\n",
        "\n",
        "# ══════════════════════════════════════════════\n",
        "#  ⑧ SAVE / LOAD MODEL\n",
        "# ══════════════════════════════════════════════\n",
        "def save_model(model: keras.Model, save_path: str) -> None:\n",
        "    \"\"\"Save trained model to Drive.\"\"\"\n",
        "    os.makedirs(os.path.dirname(save_path), exist_ok=True)\n",
        "    model.save(save_path)\n",
        "    print(f\"  ✅ Model saved → {save_path}\")\n",
        "\n",
        "\n",
        "def load_stroke_model(model_path: str) -> keras.Model:\n",
        "    \"\"\"Load a previously trained stroke detection model.\"\"\"\n",
        "    if not Path(model_path).exists():\n",
        "        print(f\"  ❌ Model not found: {model_path}\")\n",
        "        return None\n",
        "    model = keras.models.load_model(model_path)\n",
        "    print(f\"  ✅ Model loaded from {model_path}\")\n",
        "    return model\n",
        "\n",
        "\n",
